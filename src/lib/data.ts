const STAGE_BASE: Record<Stage, number> = { early: 5600, primary: 8400, middle: 11800, senior: 16500 };

/** Builds the official course-book bundle for a school + grade pair. */
export function getCourseBundle(schoolId: SchoolId, gradeId: GradeId): CourseBundle {
  const school = schoolById(schoolId);
  const grade = gradeById(gradeId);
  const step = GRADES.findIndex((g) => g.id === gradeId);
  return {
    id: `bundle-${schoolId}-${gradeId}`,
    name: `${school.short} ${grade.label} Course Pack`,
    school,
    grade,
    subjects: SUBJECTS[grade.stage],
    price: STAGE_BASE[grade.stage] + step * 250,
  };
}


